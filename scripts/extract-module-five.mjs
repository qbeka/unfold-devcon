import { promises as fs } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as pdfjsLib from "pdfjs-dist/legacy/build/pdf.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const pdfPath = join(repoRoot, "public", "manual", "abst-manual.pdf");
const outDir = join(repoRoot, "lib", "data");
const outFile = join(outDir, "moduleFiveContent.ts");

const MODULE_FIVE_RANGE = { start: 107, end: 129 };

async function main() {
  const data = new Uint8Array(await fs.readFile(pdfPath));
  const pdf = await pdfjsLib.getDocument({ data, disableFontFace: true }).promise;

  const segments = [];
  for (let pageNum = MODULE_FIVE_RANGE.start; pageNum <= MODULE_FIVE_RANGE.end; pageNum += 1) {
    const page = await pdf.getPage(pageNum);
    const content = await page.getTextContent();
    const pageLabel = `${pageNum - MODULE_FIVE_RANGE.start + 1}`;
    const lines = collapseLines(content.items);
    segments.push({ pdfPage: pageNum, pageLabel, lines });
  }

  const sections = [];
  let currentSection = createSection("Module Five: Documentation and Evidence");

  for (const segment of segments) {
    const cleaned = cleanLines(segment.lines);
    for (const line of cleaned) {
      if (isHeading(line)) {
        if (currentSection.blocks.length > 0) {
          sections.push(currentSection);
        }
        currentSection = createSection(line);
        continue;
      }

      const block = currentSection.blocks[currentSection.blocks.length - 1];
      if (line.startsWith("•") || line.startsWith("\u2022") || /^[0-9]+\.\s/.test(line)) {
        if (block?.kind !== "list") {
          currentSection.blocks.push({
            kind: "list",
            page: segment.pageLabel,
            items: []
          });
        }
        const listBlock = currentSection.blocks[currentSection.blocks.length - 1];
        listBlock.items.push(line.replace(/^[\u2022•]\s*/, "").replace(/^\d+\.\s*/, "").trim());
        continue;
      }

      if (block?.kind === "paragraph" && block.page === segment.pageLabel && !block.text.match(/[.!?:]\s*$/)) {
        block.text += " " + line;
      } else {
        currentSection.blocks.push({
          kind: "paragraph",
          page: segment.pageLabel,
          text: line
        });
      }
    }
  }

  if (currentSection.blocks.length > 0) {
    sections.push(currentSection);
  }

  // Final scrub: drop noise sections, normalize whitespace, dedupe paragraphs
  const seen = new Set();
  const finalSections = [];
  for (const section of sections) {
    const blocks = [];
    for (const block of section.blocks) {
      if (block.kind === "paragraph") {
        const normalized = block.text.replace(/\s+/g, " ").trim();
        if (normalized.length < 3) continue;
        const key = normalized.toLowerCase();
        if (seen.has(key)) continue;
        seen.add(key);
        blocks.push({ ...block, text: normalized });
      } else if (block.kind === "list") {
        const items = [];
        for (const item of block.items) {
          const normalized = item.replace(/\s+/g, " ").trim();
          if (normalized.length < 2) continue;
          const key = "list:" + normalized.toLowerCase();
          if (seen.has(key)) continue;
          seen.add(key);
          items.push(normalized);
        }
        if (items.length > 0) blocks.push({ ...block, items });
      }
    }
    if (blocks.length > 0) {
      finalSections.push({
        heading: section.heading.replace(/\s+/g, " ").trim(),
        blocks
      });
    }
  }

  await fs.mkdir(outDir, { recursive: true });
  const exportData = {
    pageRange: { start: MODULE_FIVE_RANGE.start, end: MODULE_FIVE_RANGE.end },
    sections: finalSections
  };
  const tsContent =
    "// Auto-generated by scripts/extract-module-five.mjs.\n" +
    "// Run `node scripts/extract-module-five.mjs` to refresh.\n\n" +
    "export type ModuleFiveBlock =\n" +
    "  | { kind: \"paragraph\"; page: string; text: string }\n" +
    "  | { kind: \"list\"; page: string; items: string[] };\n\n" +
    "export type ModuleFiveSection = { heading: string; blocks: ModuleFiveBlock[] };\n\n" +
    "export type ModuleFiveContent = {\n" +
    "  pageRange: { start: number; end: number };\n" +
    "  sections: ModuleFiveSection[];\n" +
    "};\n\n" +
    `export const moduleFiveContent: ModuleFiveContent = ${JSON.stringify(exportData, null, 2)};\n`;
  await fs.writeFile(outFile, tsContent, "utf8");
  console.log(`Wrote ${outFile}`);
  console.log(`Sections: ${finalSections.length}`);
}

function createSection(heading) {
  return { heading, blocks: [] };
}

function collapseLines(items) {
  const sorted = [...items].sort((a, b) => {
    if (!a.transform || !b.transform) return 0;
    const ay = a.transform[5];
    const by = b.transform[5];
    if (Math.abs(ay - by) > 4) return by - ay;
    return a.transform[4] - b.transform[4];
  });

  const lines = [];
  let buffer = [];
  let lastY = null;

  for (const item of sorted) {
    if (!item || typeof item.str !== "string") continue;
    const y = item.transform ? item.transform[5] : 0;
    if (lastY === null) {
      buffer.push(item.str);
      lastY = y;
      continue;
    }
    if (Math.abs(y - lastY) > 4) {
      lines.push(buffer.join("").trim());
      buffer = [item.str];
    } else {
      buffer.push(item.str);
    }
    lastY = y;
  }
  if (buffer.length > 0) lines.push(buffer.join("").trim());
  return lines.map((line) => line.trim()).filter(Boolean);
}

function cleanLines(lines) {
  return lines
    .map((line) => line.replace(/\s+/g, " ").trim())
    .filter((line) => {
      if (!line) return false;
      if (/Alberta Solicitor General/i.test(line)) return false;
      if (/Ministry of Public Security/i.test(line)) return false;
      if (/Alberta Basic Security Training/i.test(line)) return false;
      if (/Module (One|Two|Three|Four|Five|Six|Seven|Eight),?\s*Page/i.test(line)) return false;
      if (/^Module Five:/i.test(line) === false && /Module Five:/i.test(line)) return false;
      if (/^Page \d+/i.test(line)) return false;
      if (/^Jan-?14$/i.test(line)) return false;
      if (/^© \d{4}\./.test(line)) return false;
      if (/^Used under license/i.test(line)) return false;
      if (/^iStock #/i.test(line)) return false;
      if (line.length === 1) return false;
      return true;
    });
}

function isHeading(line) {
  if (!line) return false;
  if (line.length > 80) return false;
  if (/^Module Five:/i.test(line)) return true;
  if (/^Notebooks?$|^Reports?$|^Statements?$|^Evidence$|^Witness Statements?$|^Photographs?$|^The Phonetic Alphabet$|^Use of Force Reports?$|^Conclusion$|^Activity \d+/i.test(line)) {
    return true;
  }
  if (/^Test your knowledge/i.test(line)) return true;
  if (/^Practice #?\d+/i.test(line)) return true;
  if (/^The 24-?Hour Clock/i.test(line)) return true;
  if (/^Types of Evidence$/i.test(line)) return true;
  if (/^Court(s)?$/i.test(line)) return true;
  if (/^Sample Notebook|^Sample Report/i.test(line)) return true;
  return false;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
